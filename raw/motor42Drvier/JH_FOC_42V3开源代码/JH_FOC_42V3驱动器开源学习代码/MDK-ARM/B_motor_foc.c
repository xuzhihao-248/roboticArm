void set_duty_by_sector( foc_TypeDef *mfoc)
{
 switch(mfoc ->sector )
 {
 
	 case 1: //A+B+导通
	         HN4_set (mfoc ->Ts);HN3_set (mfoc ->Ts-mfoc ->Ta);//A+
					 HN2_set (mfoc ->Ts);HN1_set (mfoc ->Ts-mfoc ->Tb);//B+

		 break;
	 case 2: 
					//A-B+导通
					 HN3_set (mfoc ->Ts);HN4_set (mfoc ->Ts-mfoc ->Ta );//A-
	         HN2_set (mfoc ->Ts);HN1_set (mfoc ->Ts-mfoc ->Tb);//B+
		 break ;
	 case 3:					
		       //A-B-导通
					 HN3_set (mfoc ->Ts);HN4_set (mfoc ->Ts-mfoc ->Ta );//A-
	         HN1_set (mfoc ->Ts);HN2_set (mfoc ->Ts-mfoc ->Tb);//B-
		 break ;
	 case 4:		       
		       //A+B-导通
					 HN4_set (mfoc ->Ts);HN3_set (mfoc ->Ts-mfoc ->Ta );//A+
	         HN1_set (mfoc ->Ts);HN2_set (mfoc ->Ts-mfoc ->Tb);//B-
		 break ;
	 default :break ;
 
 }


}



