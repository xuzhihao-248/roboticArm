extern  float w_Uq;
extern uint8_t limit_vol;
#define Omax 8
void foc_current_pid( foc_TypeDef *mfoc)//电流pid
{
  
	
	//计算误差
	mfoc ->id_err =mfoc ->tar_Id - mfoc ->Id ;
	mfoc ->iq_err=mfoc ->tar_Iq  - mfoc ->Iq ;

	//积分项
	mfoc->id_inter+=mfoc->ki*mfoc ->id_err ;
	mfoc->iq_inter +=mfoc->ki *mfoc->iq_err ;
	
	
	  //积分限幅
	if(mfoc ->id_inter > 8 )
		mfoc->id_inter =8 ;
	if(mfoc->id_inter <-8 )
		mfoc ->id_inter =-8 ;
	
	if(mfoc ->iq_inter > 10 )
		mfoc->iq_inter =10 ;
	if(mfoc->iq_inter <-10 )
		mfoc ->iq_inter =-10 ;
	
	//计算输出值
	mfoc ->Ud = mfoc ->kp *mfoc ->id_err +  mfoc->id_inter + mfoc->kd*(mfoc->id_err -mfoc ->last_Id_err) ;
	mfoc ->Uq =mfoc ->kp *mfoc ->iq_err +  mfoc->iq_inter + mfoc->kd*(mfoc->iq_err -mfoc ->last_Iq_err)+w_Uq ;
	
	//输出限幅
	if(mfoc ->Ud  > Omax )
		mfoc->Ud =Omax ;
	if(mfoc->Ud <-Omax )
		mfoc ->Ud =-Omax ;

	if(mfoc ->Uq > Omax )
		mfoc->Uq =Omax ;
	if(mfoc->Uq <-Omax )
		mfoc ->Uq =-Omax ;
	
	mfoc ->last_Id_err =mfoc->id_err  ;	
	mfoc ->last_Iq_err =mfoc->iq_err  ;
}


